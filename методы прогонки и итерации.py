#Метод прогонки (Томаса)
#Применяется для решения СЛАУ с трехдиагональной матрицей вида:
#\(A_{i}x_{i-1}+C_{i}x_{i}+B_{i}x_{i+1}=F_{i}\)


def thomas_algorithm(A, C, B, F):
    """
    Метод прогонки для трехдиагональной СЛАУ.
    A: нижняя диагональ (длина n, A[0] не используется)
    C: главная диагональ (длина n)
    B: верхняя диагональ (длина n, B[-1] не используется)
    F: правая часть (длина n)
    """
    n = len(F)
    alpha = [0.0] * n
    beta = [0.0] * n
    x = [0.0] * n

    # Прямой ход (вычисление прогоночных коэффициентов)
    alpha[0] = -B[0] / C[0]
    beta[0] = F[0] / C[0]

    for i in range(1, n - 1):
        denominator = C[i] + A[i] * alpha[i - 1]
        alpha[i] = -B[i] / denominator
        beta[i] = (F[i] - A[i] * beta[i - 1]) / denominator

    beta[n - 1] = (F[n - 1] - A[n - 1] * beta[n - 2]) / (C[n - 1] + A[n - 1] * alpha[n - 2])

    # Обратный ход (нахождение неизвестных)
    x[n - 1] = beta[n - 1]
    for i in range(n - 2, -1, -1):
        x[i] = alpha[i] * x[i + 1] + beta[i]

    return x


# Пример использования:
# Система уравнений:
#  2x0 + 1x1       = 4
#  1x0 + 3x1 + 1x2 = 7
#        1x1 + 2x2 = 5
A_diag = [0.0, 1.0, 1.0]  # нижняя диагональ
C_diag = [2.0, 3.0, 2.0]  # главная диагональ
B_diag = [1.0, 1.0, 0.0]  # верхняя диагональ
F_vector = [4.0, 7.0, 5.0]

sol_thomas = thomas_algorithm(A_diag, C_diag, B_diag, F_vector)
print("Результат метода прогонки:", [round(el, 4) for el in sol_thomas])
# Ожидаемый ответ: [1.0, 2.0, 1.5]




#Метод простой итерации (Якоби)
#Используется для квадратных матриц. Для сходимости метода матрица должна обладать диагональным преобладанием.

def jacobi_iteration(M, F, eps=1e-5, max_steps=100):
    """
    Метод простой итерации (Якоби) для СЛАУ M * x = F.
    M: квадратная матрица (список списков)
    F: вектор правой части
    eps: точность (критерий остановки)
    max_steps: максимальное число итераций
    """
    n = len(F)
    x = [0.0] * n  # Начальное приближение (нули)

    for step in range(max_steps):
        x_new = [0.0] * n
        for i in range(n):
            # Вычисляем сумму элементов строки, кроме главного диагонального
            row_sum = sum(M[i][j] * x[j] for j in range(n) if i != j)
            # Формула x_i = (F_i - sum(M_ij * x_j)) / M_ii
            x_new[i] = (F[i] - row_sum) / M[i][i]

        # Проверка условия сходимости (норма разности векторов)
        diff = max(abs(x_new[k] - x[k]) for k in range(n))
        if diff < eps:
            print(converge_msg := f"Метод сошелся за {step + 1} итераций.")
            return x_new

        x = x_new

    print("Достигнуто максимальное число итераций без сходимости.")
    return x


# Пример использования (с выраженным диагональным преобладанием):
# 10x0 +  1x1 -  x2 = 10
#  x0 + 10x1 +  x2 = 12
#  x0 +  x1 + 10x2 = 12
Matrix = [
    [10.0, 1.0, -1.0],
    [1.0, 10.0, 1.0],
    [1.0, 1.0, 10.0]
]
F_vec = [10.0, 12.0, 12.0]

sol_iter = jacobi_iteration(Matrix, F_vec)
print("Результат метода итераций:", [round(el, 4) for el in sol_iter])
# Ожидаемый ответ: [1.0, 1.0, 1.0]
